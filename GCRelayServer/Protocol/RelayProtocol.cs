namespace GCRelayServer.Protocol;

public enum RelaySenderRole
{
    None,
    AnyMember,
    Host,
    Guest,
    Membership
}

public sealed record RelayModeRule(int PayloadSize, RelaySenderRole SenderRole, bool RequiresZeroPayload = false);

public sealed record RelayMessageRule(
    bool ClientMaySend,
    IReadOnlyDictionary<ushort, RelayModeRule> Modes);

public static class RelayProtocol
{
    private static readonly IReadOnlyDictionary<RelayMessageType, RelayMessageRule> Rules =
        new Dictionary<RelayMessageType, RelayMessageRule>
        {
            [RelayMessageType.PhaseBarrier] = Client(4, 4, RelaySenderRole.AnyMember),
            [RelayMessageType.MusicSelection] = Client(
                (1, new RelayModeRule(12, RelaySenderRole.Host)),
                (2, new RelayModeRule(12, RelaySenderRole.Guest))),
            [RelayMessageType.MusicSelectionCommit] = Client(4, 12, RelaySenderRole.AnyMember),
            [RelayMessageType.DifficultyAndItem] = Client(4, 8, RelaySenderRole.AnyMember),
            [RelayMessageType.LiveTuneSnapshot] = Client(
                (1, new RelayModeRule(84, RelaySenderRole.Host)),
                (2, new RelayModeRule(24, RelaySenderRole.Guest))),
            [RelayMessageType.ResultRecord] = Client(4, 88, RelaySenderRole.AnyMember),
            [RelayMessageType.PresetMessage] = Client(4, 4, RelaySenderRole.AnyMember),
            [RelayMessageType.GuestLiveness] = Client(2, 8, RelaySenderRole.Guest, requiresZeroPayload: true),
            [RelayMessageType.HostStatus] = Client(1, 16, RelaySenderRole.Host),
            [RelayMessageType.Registration] = Client(0, 256, RelaySenderRole.Membership),
            [RelayMessageType.RegistrationAck] = Output(0, 256),
            [RelayMessageType.NewMember] = Output(4, 256),
            [RelayMessageType.Leave] = Client(0, 8, RelaySenderRole.Membership, requiresZeroPayload: true),
            [RelayMessageType.Announcement] = Client(4, 256, RelaySenderRole.Membership),
            [RelayMessageType.Start] = Client(1, 8, RelaySenderRole.Host, requiresZeroPayload: true),
            [RelayMessageType.HeartbeatRequest] = Client(0, 8, RelaySenderRole.None, requiresZeroPayload: true),
            [RelayMessageType.HeartbeatResponse] = Output(0, 8, requiresZeroPayload: true)
        };

    public static bool TryGetRule(RelayMessageType messageType, out RelayMessageRule rule)
    {
        return Rules.TryGetValue(messageType, out rule!);
    }

    public static bool TryValidateClient(RelayDatagram datagram, out RelayRejection rejection)
    {
        if (!TryGetRule(datagram.MessageType, out var rule))
        {
            rejection = new RelayRejection(RelayRejectionCode.UnknownMessage, "Subtype is not in the native inventory.");
            return false;
        }

        if (!rule.ClientMaySend)
        {
            rejection = new RelayRejection(
                RelayRejectionCode.OutputOnlyMessage,
                $"{datagram.MessageType} is generated by the relay.");
            return false;
        }

        return TryValidateContract(datagram, rule, out rejection);
    }

    public static bool TryValidateForEncoding(RelayDatagram datagram, out RelayRejection rejection)
    {
        if (!TryGetRule(datagram.MessageType, out var rule))
        {
            rejection = new RelayRejection(RelayRejectionCode.UnknownMessage, "Subtype is not in the native inventory.");
            return false;
        }

        return TryValidateContract(datagram, rule, out rejection);
    }

    public static RelaySenderRole GetSenderRole(RelayDatagram datagram)
    {
        return Rules[datagram.MessageType].Modes[datagram.Mode].SenderRole;
    }

    private static bool TryValidateContract(
        RelayDatagram datagram,
        RelayMessageRule rule,
        out RelayRejection rejection)
    {
        if (!rule.Modes.TryGetValue(datagram.Mode, out var modeRule))
        {
            rejection = new RelayRejection(
                RelayRejectionCode.InvalidMode,
                $"Mode {datagram.Mode} is invalid for {datagram.MessageType}.");
            return false;
        }

        if (datagram.PayloadSize != modeRule.PayloadSize)
        {
            rejection = new RelayRejection(
                RelayRejectionCode.InvalidPayloadContract,
                $"{datagram.MessageType}/{datagram.Mode} requires {modeRule.PayloadSize} payload bytes.");
            return false;
        }

        if (modeRule.RequiresZeroPayload && datagram.Payload.Span.IndexOfAnyExcept((byte)0) >= 0)
        {
            rejection = new RelayRejection(
                RelayRejectionCode.NonZeroReservedPayload,
                $"{datagram.MessageType} requires a zero-filled payload.");
            return false;
        }

        rejection = RelayRejection.None;
        return true;
    }

    private static RelayMessageRule Client(
        ushort mode,
        int payloadSize,
        RelaySenderRole senderRole,
        bool requiresZeroPayload = false)
    {
        return new RelayMessageRule(
            true,
            new Dictionary<ushort, RelayModeRule>
            {
                [mode] = new(payloadSize, senderRole, requiresZeroPayload)
            });
    }

    private static RelayMessageRule Client(params (ushort Mode, RelayModeRule Rule)[] modes)
    {
        return new RelayMessageRule(true, modes.ToDictionary(item => item.Mode, item => item.Rule));
    }

    private static RelayMessageRule Output(ushort mode, int payloadSize, bool requiresZeroPayload = false)
    {
        return new RelayMessageRule(
            false,
            new Dictionary<ushort, RelayModeRule>
            {
                [mode] = new(payloadSize, RelaySenderRole.None, requiresZeroPayload)
            });
    }
}
